"""Unit checks for standardized feature provenance descriptions."""

from __future__ import annotations

import unittest
import json
import tempfile
from pathlib import Path

from generic_converter.metadata import (
    annotate_dataset_info,
    annotate_features,
    validate_feature_descriptions,
)


class MetadataTest(unittest.TestCase):
    def test_annotations_cover_top_level_and_nested_descriptions(self) -> None:
        features = {
            "action.qpos": {
                "dtype": "float32",
                "shape": (2,),
                "description": "Commanded positions.",
                "field_descriptions": {
                    "left": {"description": "Left command."},
                },
            }
        }
        result = annotate_features(
            features,
            embodiment="test-arm",
            origins={"action.qpos": "raw/action/qpos"},
        )
        validate_feature_descriptions(result)
        self.assertIn(
            "Embodiment: test-arm.", result["action.qpos"]["description"]
        )
        self.assertIn(
            "OriginData: raw/action/qpos.", result["action.qpos"]["description"]
        )
        nested = result["action.qpos"]["field_descriptions"]["left"][
            "description"
        ]
        self.assertIn("Embodiment: test-arm.", nested)
        self.assertIn("OriginData: raw/action/qpos.", nested)

    def test_missing_description_receives_fallback(self) -> None:
        result = annotate_features(
            {
                "observation.images.top": {
                    "dtype": "video",
                    "shape": (1, 1, 3),
                }
            },
            embodiment="test-arm",
            origins={"observation.images.top": "raw/images/top"},
        )
        validate_feature_descriptions(result)

    def test_recursive_validation_rejects_unannotated_nested_description(self) -> None:
        features = {
            "action.qpos": {
                "description": (
                    "Command. Embodiment: test-arm. OriginData: raw/action/qpos."
                ),
                "field_descriptions": {"left": {"description": "Left command."}},
            }
        }
        with self.assertRaisesRegex(ValueError, "Embodiment"):
            validate_feature_descriptions(features)

    def test_dataset_info_adds_provenance_to_lerobot_generated_features(self) -> None:
        with tempfile.TemporaryDirectory() as temp_dir:
            info_path = Path(temp_dir) / "meta" / "info.json"
            info_path.parent.mkdir()
            info_path.write_text(
                json.dumps(
                    {
                        "features": {
                            "action.qpos": {
                                "description": (
                                    "Command. Embodiment: test-arm. "
                                    "OriginData: raw/action/qpos."
                                )
                            },
                            "timestamp": {
                                "description": "Timestamp in seconds."
                            },
                        }
                    }
                ),
                encoding="utf-8",
            )

            annotate_dataset_info(temp_dir)

            info = json.loads(info_path.read_text(encoding="utf-8"))
            timestamp = info["features"]["timestamp"]["description"]
            self.assertIn("Embodiment: test-arm.", timestamp)
            self.assertIn(
                "OriginData: generated by LeRobot from frame_index and dataset fps.",
                timestamp,
            )


if __name__ == "__main__":
    unittest.main()
